#!/bin/sh

# ------------------------------------------------------------
# Настройки
# ------------------------------------------------------------

LOG="/var/log/dns-auto.log"
LOCK="/tmp/dns-auto.lock"

# Через сколько часов полностью очищать лог
LOG_RETENTION_HOURS=1

WAN="wan"

DOMAINS="
youtube.com
instagram.com
telegram.org
yandex.ru
"

# ------------------------------------------------------------
# DNS кандидаты
# ------------------------------------------------------------

DNS_SERVERS="
1.1.1.1
1.0.0.1
8.8.8.8
8.8.4.4
9.9.9.9
149.112.112.112
94.140.14.14
94.140.15.15
77.88.8.8
77.88.8.1
208.67.222.222
208.67.220.220
"

MIN_OK=3

# ------------------------------------------------------------
# Логи
# ------------------------------------------------------------

log()
{
    echo "$(date '+%Y-%m-%d %H:%M:%S') $*" >> "$LOG"
}

# ------------------------------------------------------------
# Автоматическая очистка лога
# ------------------------------------------------------------

LOG_CLEANUP_STATE="/root/dns-auto-log-cleanup"

cleanup_log()
{
    NOW="$(date +%s)"

    # Первый запуск - создаём файл состояния
    if [ ! -f "$LOG_CLEANUP_STATE" ]; then
        echo "$NOW" > "$LOG_CLEANUP_STATE"
        return 0
    fi

    LAST_CLEANUP="$(cat "$LOG_CLEANUP_STATE" 2>/dev/null)"

    # Если значение некорректное - начинаем отсчёт заново
    case "$LAST_CLEANUP" in
        ''|*[!0-9]*)
            echo "$NOW" > "$LOG_CLEANUP_STATE"
            return 0
            ;;
    esac

    # Проверяем, прошло ли нужное количество часов
    if [ $((NOW - LAST_CLEANUP)) -ge $((LOG_RETENTION_HOURS * 3600)) ]; then

        # Полностью очищаем лог
        : > "$LOG"

        # Запоминаем время очистки
        echo "$NOW" > "$LOG_CLEANUP_STATE"

        # Сообщение после очистки
        log "===== Лог очищен, так как прошло: ${LOG_RETENTION_HOURS} часа(ов)====="
    fi
}

# ------------------------------------------------------------
# LOCK
# ------------------------------------------------------------

if [ -e "$LOCK" ]; then
    exit 0
fi

touch "$LOCK"
trap 'rm -f "$LOCK"' EXIT

# ------------------------------------------------------------
# Очистка старого лога
# ------------------------------------------------------------

cleanup_log

# ------------------------------------------------------------
# Старт
# ------------------------------------------------------------

log "===== DNS AUTO CHECK START ====="

# ------------------------------------------------------------
# Проверка DNS сервера
# ------------------------------------------------------------

test_dns()
{
    DNS="$1"
    OK=0

    for DOMAIN in $DOMAINS; do

        RESULT="$(nslookup "$DOMAIN" "$DNS" 2>&1)"

        if echo "$RESULT" | grep -Eq \
            'Address [0-9]+:|Address: [0-9]+\.[0-9]+\.[0-9]+\.[0-9]+|has address|Name:'
        then
            OK=$((OK + 1))
        fi

    done

    echo "$OK"
}

# ------------------------------------------------------------
# Проверка текущего DNS
# ------------------------------------------------------------

test_current()
{
    OK=0

    for DOMAIN in $DOMAINS; do
        if nslookup "$DOMAIN" >/dev/null 2>&1; then
            OK=$((OK + 1))
        fi
    done

    echo "$OK"
}

# ------------------------------------------------------------
# Проверяем текущий DNS
# ------------------------------------------------------------

DOMAIN_COUNT="$(echo "$DOMAINS" | wc -w)"
CURRENT_OK="$(test_current)"

log "Чекаем текущий DNS: $CURRENT_OK/$DOMAIN_COUNT"

if [ "$CURRENT_OK" -ge "$MIN_OK" ]; then
    log "С текущим DNS все норм, ошибок нет, все пингуется, оставляем как было."
    log "===== DNS AUTO CHECK END ====="
    exit 0
fi

log "Текущий DNS сдох, ищем другой..."

# ------------------------------------------------------------
# Перебор DNS
# ------------------------------------------------------------

BEST_DNS=""
BEST_SCORE=0

for DNS in $DNS_SERVERS; do

    SCORE="$(test_dns "$DNS")"

    log "DNS $DNS -> $SCORE/$DOMAIN_COUNT"

    # Выбираем DNS, который успешно резолвит
    # максимальное количество доменов
    if [ "$SCORE" -gt "$BEST_SCORE" ]; then
        BEST_SCORE="$SCORE"
        BEST_DNS="$DNS"
    fi

    # Рабочий DNS найден
    if [ "$SCORE" -eq "$DOMAIN_COUNT" ]; then
        break
    fi

done

# ------------------------------------------------------------
# Все лежит
# ------------------------------------------------------------

if [ -z "$BEST_DNS" ] || [ "$BEST_SCORE" -lt "$MIN_OK" ]; then
    log "Курим бамбук, мы в чебурнете, ждем некст трай, возможно станет лучше..."
    log "===== DNS AUTO CHECK END ====="
    exit 1
fi

log "Найден DNS: $BEST_DNS ($BEST_SCORE/$DOMAIN_COUNT)"

# ------------------------------------------------------------
# Проверяем текущую конфигурацию
# ------------------------------------------------------------

CURRENT_CONFIG="$(uci -q get network.$WAN.dns 2>/dev/null)"

if echo "$CURRENT_CONFIG" | grep -qw "$BEST_DNS"; then
    log "DNS $BEST_DNS уже был. Оставляем как было, не трогаем, чтобы не сделать хуже."
    log "===== DNS AUTO CHECK END ====="
    exit 0
fi

# ------------------------------------------------------------
# Меняем конфиг
# ------------------------------------------------------------

log "Применяю DNS $BEST_DNS..."

# Не использовать DNS, полученный от DHCP
uci set network.$WAN.peerdns='0'

# Удаляем старые DNS
uci -q delete network.$WAN.dns

# Добавляем найденный DNS
uci add_list network.$WAN.dns="$BEST_DNS"

# Сохраняем конфигурацию
uci commit network

log "Перезапуск сети..."

/etc/init.d/network reload

sleep 5

# ------------------------------------------------------------
# Финальная проверка
# ------------------------------------------------------------

FINAL_OK="$(test_dns "$BEST_DNS")"

if [ "$FINAL_OK" -ge "$MIN_OK" ]; then
    log "Этот четкий, стильный, модный, молодежный (или не очень) DNS $BEST_DNS точно работает, ну, по крайней мере оно пингует нормально домены из скриптика ($FINAL_OK/$DOMAIN_COUNT)"
else
    log "!!!Внимание!!!: выбран DNS $BEST_DNS, но результат ласт проверки: $FINAL_OK/$DOMAIN_COUNT"
fi

log "===== DNS AUTO CHECK END ====="

exit 0
